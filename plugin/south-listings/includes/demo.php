<?php
/**
 * One-click demo content: the South template's nine homes, its three agents
 * and its three journal posts, with their photographs.
 *
 * The listing grids are dynamic, so a new site would otherwise show empty
 * states everywhere and look broken rather than new. Demo photographs ship in
 * this plugin (demo/images), never in the theme, and go into the media
 * library like any upload. Nothing is overwritten: every item is matched on
 * its slug first, so running the import twice creates nothing new. What it
 * created is recorded, and "Remove demo content" deletes exactly that.
 *
 *   Properties > Demo content          in the admin
 *   wp south-listings demo [--remove]  with WP-CLI
 *
 * @package South_Listings
 */

defined( 'ABSPATH' ) || exit;

/** Option recording what the import created: type => [ids]. */
const SOUTH_LISTINGS_DEMO_OPTION = 'south_listings_demo';

/**
 * The demo data (generated by .dev/build_demo.py).
 *
 * @return array
 */
function south_listings_demo_data() {
	return require south_listings_path( 'demo/data.php' );
}

/**
 * Find an existing post by slug and type (never get_page_by_path(), which
 * also matches attachments: Pato's importer skipped every post that way).
 *
 * @param string $slug Slug.
 * @param string $type Post type.
 * @return int
 */
function south_listings_demo_find( $slug, $type ) {
	$found = get_posts(
		array(
			'name'           => $slug,
			'post_type'      => $type,
			'post_status'    => array( 'publish', 'draft', 'pending', 'private', 'future' ),
			'posts_per_page' => 1,
			'fields'         => 'ids',
		)
	);
	return $found ? (int) $found[0] : 0;
}

/**
 * Copy one demo image into the media library.
 *
 * @param string $file    File name in demo/images.
 * @param int    $post_id Parent post.
 * @param string $alt     Alternative text, written from the picture.
 * @return int Attachment ID, or 0.
 */
function south_listings_demo_image( $file, $post_id, $alt ) {
	require_once ABSPATH . 'wp-admin/includes/file.php';
	require_once ABSPATH . 'wp-admin/includes/media.php';
	require_once ABSPATH . 'wp-admin/includes/image.php';

	$source = south_listings_path( 'demo/images/' . $file );
	if ( ! is_readable( $source ) ) {
		return 0;
	}
	$tmp = wp_tempnam( $file );
	if ( ! $tmp || ! copy( $source, $tmp ) ) {
		return 0;
	}
	$id = media_handle_sideload(
		array(
			'name'     => $file,
			'tmp_name' => $tmp,
		),
		$post_id,
		$alt
	);
	if ( is_wp_error( $id ) ) {
		wp_delete_file( $tmp );
		return 0;
	}
	update_post_meta( $id, '_wp_attachment_image_alt', $alt );
	return (int) $id;
}

/**
 * A term, created if missing.
 *
 * @param string $name     Name.
 * @param string $taxonomy Taxonomy.
 * @return int
 */
function south_listings_demo_term( $name, $taxonomy ) {
	$slug = sanitize_title( $name );
	$term = get_term_by( 'slug', $slug, $taxonomy );
	if ( $term ) {
		return (int) $term->term_id;
	}
	$made = wp_insert_term( $name, $taxonomy, array( 'slug' => $slug ) );
	return is_wp_error( $made ) ? 0 : (int) $made['term_id'];
}

/**
 * Paragraph blocks from plain sentences.
 *
 * @param string[] $paragraphs Paragraphs.
 * @return string
 */
function south_listings_demo_paragraphs( $paragraphs ) {
	$out = '';
	foreach ( $paragraphs as $text ) {
		$out .= "<!-- wp:paragraph -->\n<p>" . esc_html( $text ) . "</p>\n<!-- /wp:paragraph -->\n\n";
	}
	return $out;
}

/**
 * Run the import.
 *
 * @return array{agents:int, homes:int, posts:int, images:int}
 */
function south_listings_import_demo() {
	south_listings_register();
	south_listings_ensure_terms();

	$data    = south_listings_demo_data();
	$made    = get_option( SOUTH_LISTINGS_DEMO_OPTION, array() );
	$made    = is_array( $made ) ? $made : array();
	$counts  = array(
		'agents' => 0,
		'homes'  => 0,
		'posts'  => 0,
		'images' => 0,
	);
	$record  = static function ( $type, $id ) use ( &$made ) {
		$made[ $type ][] = (int) $id;
	};
	$sale_id = (int) get_term_by( 'slug', 'sale', 'property_status' )->term_id;
	$rent_id = (int) get_term_by( 'slug', 'rent', 'property_status' )->term_id;

	// Agents.
	$agents = array();
	foreach ( $data['agents'] as $agent ) {
		$id = south_listings_demo_find( $agent['slug'], 'south_agent' );
		if ( ! $id ) {
			$id = wp_insert_post(
				array(
					'post_type'   => 'south_agent',
					'post_status' => 'publish',
					'post_title'  => $agent['name'],
					'post_name'   => $agent['slug'],
				)
			);
			if ( is_wp_error( $id ) || ! $id ) {
				continue;
			}
			$record( 'posts', $id );
			update_post_meta( $id, 'south_agent_role', $agent['role'] );
			update_post_meta( $id, 'south_agent_phone', $agent['phone'] );
			update_post_meta( $id, 'south_agent_email', $agent['email'] );
			$photo = south_listings_demo_image( $agent['photo'], $id, $agent['alt'] );
			if ( $photo ) {
				set_post_thumbnail( $id, $photo );
				$record( 'attachments', $photo );
				++$counts['images'];
			}
			++$counts['agents'];
		}
		$agents[ $agent['slug'] ] = (int) $id;
	}

	// Homes.
	foreach ( $data['homes'] as $home ) {
		if ( south_listings_demo_find( $home['slug'], 'property' ) ) {
			continue;
		}
		$id = wp_insert_post(
			array(
				'post_type'    => 'property',
				'post_status'  => 'publish',
				'post_title'   => $home['title'],
				'post_name'    => $home['slug'],
				// wp_insert_post() unslashes; block markup must go in slashed.
				'post_content' => wp_slash( south_listings_demo_paragraphs( $home['description'] ) ),
				'post_excerpt' => $home['summary'],
				'post_date'    => $home['listed'],
				'menu_order'   => (int) $home['order'],
			)
		);
		if ( is_wp_error( $id ) || ! $id ) {
			continue;
		}
		$record( 'posts', $id );

		$meta = array(
			'south_price'         => $home['price'],
			'south_rent_period'   => 'month',
			'south_reference'     => $home['reference'],
			'south_featured'      => $home['featured'] ? '1' : '',
			'south_new'           => $home['new'] ? '1' : '',
			'south_beds'          => $home['beds'],
			'south_baths'         => $home['baths'],
			'south_garages'       => $home['garages'],
			'south_area'          => $home['area'],
			'south_year'          => $home['year'],
			'south_address'       => $home['address'],
			'south_neighbourhood' => $home['neighbourhood'],
			'south_lat'           => $home['lat'],
			'south_lon'           => $home['lon'],
			'south_outdoor'       => $home['outdoor'],
			'south_view'          => $home['view'],
			'south_furnished'     => $home['furnished'] ? '1' : '',
			'south_pets'          => $home['pets'] ? '1' : '',
			'south_features'      => implode( "\n", $home['features'] ),
			'south_rooms'         => implode( "\n", $home['rooms'] ),
			'south_agent'         => isset( $agents[ $home['agent'] ] ) ? $agents[ $home['agent'] ] : 0,
		);
		foreach ( $meta as $key => $value ) {
			update_post_meta( $id, $key, $value );
		}

		wp_set_object_terms( $id, array( 'rent' === $home['status'] ? $rent_id : $sale_id ), 'property_status' );
		wp_set_object_terms( $id, array( south_listings_demo_term( $home['type'], 'property_type' ) ), 'property_type' );
		wp_set_object_terms( $id, array( south_listings_demo_term( $home['city'], 'property_city' ) ), 'property_city' );

		$thumb = south_listings_demo_image( $home['image'], $id, $home['alt'] );
		if ( $thumb ) {
			set_post_thumbnail( $id, $thumb );
			$record( 'attachments', $thumb );
			++$counts['images'];
		}
		$gallery = array();
		foreach ( $home['gallery'] as $file ) {
			$photo = south_listings_demo_image( $file, $id, $home['alt'] );
			if ( $photo ) {
				$gallery[] = $photo;
				$record( 'attachments', $photo );
				++$counts['images'];
			}
		}
		update_post_meta( $id, 'south_gallery', implode( ',', $gallery ) );
		++$counts['homes'];
	}

	// Journal posts, written by the agents.
	foreach ( $data['posts'] as $post ) {
		if ( south_listings_demo_find( $post['slug'], 'post' ) ) {
			continue;
		}
		$author = south_listings_demo_author( $post['author'], $made );
		$id     = wp_insert_post(
			array(
				'post_type'     => 'post',
				'post_status'   => 'publish',
				'post_title'    => $post['title'],
				'post_name'     => $post['slug'],
				'post_excerpt'  => $post['excerpt'],
				'post_date'     => $post['date'],
				'post_author'   => $author ? $author : get_current_user_id(),
				'post_category' => array( south_listings_demo_term( $post['category'], 'category' ) ),
				'post_content'  => '',
			)
		);
		if ( is_wp_error( $id ) || ! $id ) {
			continue;
		}
		$record( 'posts', $id );

		$content = '';
		foreach ( $post['body'] as $block ) {
			if ( 'h2' === $block[0] ) {
				$content .= "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">" . esc_html( $block[1] ) . "</h2>\n<!-- /wp:heading -->\n\n";
			} elseif ( 'img' === $block[0] ) {
				$image = south_listings_demo_image( $block[1], $id, $block[2] );
				if ( $image ) {
					$record( 'attachments', $image );
					++$counts['images'];
					$content .= '<!-- wp:image {"id":' . $image . ',"sizeSlug":"large","linkDestination":"none"} -->' . "\n"
						. '<figure class="wp-block-image size-large">' . wp_get_attachment_image( $image, 'large', false, array( 'class' => 'wp-image-' . $image ) ) . "</figure>\n<!-- /wp:image -->\n\n";
				}
			} else {
				$content .= "<!-- wp:paragraph -->\n<p>" . esc_html( $block[1] ) . "</p>\n<!-- /wp:paragraph -->\n\n";
			}
		}
		wp_update_post(
			array(
				'ID'           => $id,
				'post_content' => wp_slash( $content ),
			)
		);

		$thumb = south_listings_demo_image( $post['image'], $id, $post['alt'] );
		if ( $thumb ) {
			set_post_thumbnail( $id, $thumb );
			$record( 'attachments', $thumb );
			++$counts['images'];
		}

		$comment_ids = array();
		foreach ( $post['comments'] as $comment ) {
			$parent        = null !== $comment[3] && isset( $comment_ids[ $comment[3] ] ) ? $comment_ids[ $comment[3] ] : 0;
			$comment_ids[] = wp_insert_comment(
				array(
					'comment_post_ID'      => $id,
					'comment_author'       => $comment[0],
					'comment_author_email' => '',
					'comment_content'      => $comment[2],
					'comment_date'         => $comment[1],
					'comment_date_gmt'     => get_gmt_from_date( $comment[1] ),
					'comment_parent'       => $parent,
					'comment_approved'     => 1,
				)
			);
		}
		++$counts['posts'];
	}

	update_option( SOUTH_LISTINGS_DEMO_OPTION, $made, false );
	south_listings_demo_menu();
	flush_rewrite_rules();

	return $counts;
}

/**
 * The journal's author: a user with the agent's name, created once (role
 * Author, no password anyone knows) so the byline reads as in the template.
 *
 * @param string $name Display name.
 * @param array  $made The record of created items (by reference).
 * @return int User ID, or 0.
 */
function south_listings_demo_author( $name, &$made ) {
	$login = sanitize_user( strtolower( str_replace( ' ', '.', $name ) ), true );
	$user  = get_user_by( 'login', $login );
	if ( $user ) {
		return (int) $user->ID;
	}
	if ( ! apply_filters( 'south_listings_demo_create_authors', true ) ) {
		return 0;
	}
	$id = wp_insert_user(
		array(
			'user_login'   => $login,
			'user_pass'    => wp_generate_password( 32 ),
			'display_name' => $name,
			'first_name'   => strtok( $name, ' ' ),
			'role'         => 'author',
		)
	);
	if ( is_wp_error( $id ) ) {
		return 0;
	}
	$made['users'][] = (int) $id;
	return (int) $id;
}

/**
 * "Properties" and a "Find a Home" menu in the South navigation, as the
 * template's header has them.
 */
function south_listings_demo_menu() {
	south_listings_add_menu_link();
	$menus = get_posts(
		array(
			'post_type'      => 'wp_navigation',
			'name'           => 'south-primary',
			'post_status'    => 'publish',
			'posts_per_page' => 1,
		)
	);
	if ( ! $menus || false !== strpos( $menus[0]->post_content, 'south-nav-find' ) ) {
		return;
	}
	$links = array(
		__( 'Homes for sale', 'south-listings' )     => '/listings/?status=sale',
		__( 'Homes to rent', 'south-listings' )      => '/listings/?status=rent',
		__( 'Villas for sale', 'south-listings' )    => '/listings/?status=sale&type=villa',
		__( 'Apartments to rent', 'south-listings' ) => '/listings/?status=rent&type=apartment',
		__( 'Furnished rentals', 'south-listings' )  => '/listings/?status=rent&furnished=yes',
	);
	$items = '';
	foreach ( $links as $label => $path ) {
		$items .= sprintf( '<!-- wp:navigation-link {"label":"%s","url":"%s","kind":"custom"} /-->', esc_attr( $label ), esc_url( home_url( $path ) ) );
	}
	$submenu = sprintf(
		'<!-- wp:navigation-submenu {"label":"%s","url":"%s","kind":"custom","className":"south-nav-find"} -->%s<!-- /wp:navigation-submenu -->',
		esc_attr__( 'Find a Home', 'south-listings' ),
		esc_url( home_url( '/listings/' ) ),
		$items
	);
	$content = $menus[0]->post_content;
	// Before the last item (Contact), or at the end.
	$position = strrpos( $content, '<!-- wp:navigation-link' );
	$content  = false === $position ? $content . $submenu : substr( $content, 0, $position ) . $submenu . substr( $content, $position );
	wp_update_post(
		array(
			'ID'           => $menus[0]->ID,
			'post_content' => wp_slash( $content ),
		)
	);
}

/**
 * Delete what the import created, and nothing else.
 *
 * @return int Items deleted.
 */
function south_listings_remove_demo() {
	$made  = get_option( SOUTH_LISTINGS_DEMO_OPTION, array() );
	$count = 0;
	foreach ( array( 'posts', 'attachments' ) as $type ) {
		foreach ( isset( $made[ $type ] ) ? $made[ $type ] : array() as $id ) {
			if ( 'attachments' === $type ? wp_delete_attachment( $id, true ) : wp_delete_post( $id, true ) ) {
				++$count;
			}
		}
	}
	if ( ! empty( $made['users'] ) ) {
		require_once ABSPATH . 'wp-admin/includes/user.php';
		foreach ( $made['users'] as $id ) {
			if ( wp_delete_user( $id ) ) {
				++$count;
			}
		}
	}
	delete_option( SOUTH_LISTINGS_DEMO_OPTION );
	return $count;
}

/**
 * The admin screen.
 */
function south_listings_demo_page() {
	add_submenu_page(
		'edit.php?post_type=property',
		__( 'Demo content', 'south-listings' ),
		__( 'Demo content', 'south-listings' ),
		'manage_options',
		'south-listings-demo',
		'south_listings_demo_screen'
	);
}
add_action( 'admin_menu', 'south_listings_demo_page' );

/**
 * Render the screen.
 */
function south_listings_demo_screen() {
	$made = get_option( SOUTH_LISTINGS_DEMO_OPTION, array() );
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- display only.
	$done = isset( $_GET['south-demo'] ) ? sanitize_key( wp_unslash( $_GET['south-demo'] ) ) : '';
	echo '<div class="wrap"><h1>' . esc_html__( 'Demo content', 'south-listings' ) . '</h1>';
	if ( 'imported' === $done ) {
		echo '<div class="notice notice-success"><p>' . esc_html__( 'The demo homes, agents and journal posts are in place.', 'south-listings' ) . '</p></div>';
	} elseif ( 'removed' === $done ) {
		echo '<div class="notice notice-success"><p>' . esc_html__( 'The demo content has been removed.', 'south-listings' ) . '</p></div>';
	}
	echo '<p>' . esc_html__( 'Adds the South template\'s nine homes (six featured), three agents and three journal posts with their photographs, and adds Properties and Find a Home to the South menu. The journal posts are written by three new Author accounts named after the agents. Nothing you have made is changed, and running it again adds nothing new.', 'south-listings' ) . '</p>';
	echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '">';
	wp_nonce_field( 'south_listings_demo' );
	echo '<input type="hidden" name="action" value="south_listings_demo">';
	submit_button( __( 'Import demo content', 'south-listings' ), 'primary', 'import', false );
	if ( $made ) {
		echo ' ';
		submit_button( __( 'Remove demo content', 'south-listings' ), 'delete', 'remove', false );
	}
	echo '</form></div>';
}

/**
 * Handle the screen's buttons.
 */
function south_listings_demo_handle() {
	if ( ! current_user_can( 'manage_options' ) ) {
		wp_die( esc_html__( 'You are not allowed to do that.', 'south-listings' ) );
	}
	check_admin_referer( 'south_listings_demo' );
	if ( isset( $_POST['remove'] ) ) {
		south_listings_remove_demo();
		$result = 'removed';
	} else {
		south_listings_import_demo();
		$result = 'imported';
	}
	wp_safe_redirect( admin_url( 'edit.php?post_type=property&page=south-listings-demo&south-demo=' . $result ) );
	exit;
}
add_action( 'admin_post_south_listings_demo', 'south_listings_demo_handle' );

if ( defined( 'WP_CLI' ) && WP_CLI ) {
	/**
	 * Import or remove the demo content.
	 *
	 * ## OPTIONS
	 *
	 * [--remove]
	 * : Delete what a previous import created.
	 *
	 * @param array $args       Positional arguments.
	 * @param array $assoc_args Flags.
	 */
	function south_listings_cli_demo( $args, $assoc_args ) {
		if ( ! empty( $assoc_args['remove'] ) ) {
			WP_CLI::success( sprintf( '%d items removed.', south_listings_remove_demo() ) );
			return;
		}
		$counts = south_listings_import_demo();
		WP_CLI::success( sprintf( '%d agents, %d homes, %d posts, %d images.', $counts['agents'], $counts['homes'], $counts['posts'], $counts['images'] ) );
	}
	WP_CLI::add_command( 'south-listings demo', 'south_listings_cli_demo' );
}
